const fs = require('node:fs');
const path = require('node:path');
const CanvasKitInit = require('canvaskit-wasm/bin/full/canvaskit.js');

const root = path.resolve(path.dirname(process.argv[1]), '..');
const board = fs.readFileSync(path.join(root, 'docs', 'GAME_EXPERIENCE_BOARD.html'), 'utf8');
const world = board.match(/<symbol id="relay-world"[^>]*>([\s\S]*?)<\/symbol>/)?.[1];
if (!world) throw new Error('Experience Board Relay world is missing.');

CanvasKitInit({}).then(ck => {
  const color = (hex, opacity = 1) => ck.Color(
    parseInt(hex.slice(1, 3), 16), parseInt(hex.slice(3, 5), 16), parseInt(hex.slice(5, 7), 16), opacity,
  );
  const gradients = {
    sky: ck.Shader.MakeLinearGradient([0, 0], [0, 820],
      [color('#081320'), color('#3b1829'), color('#08111c')], [0, .45, 1], ck.TileMode.Clamp),
    core: ck.Shader.MakeRadialGradient([213, 355], 220,
      [color('#ff5465', .85), color('#ff354f', .35), color('#ff354f', 0)], [0, .55, 1], ck.TileMode.Clamp),
  };
  const surface = ck.MakeSurface(1170, 2460);
  if (!surface) throw new Error('Could not create the reference scene raster surface.');
  const canvas = surface.getCanvas();
  canvas.scale(3, 3);
  const paint = new ck.Paint();
  paint.setAntiAlias(true);
  for (const [, tag, text] of world.matchAll(/<(path|circle)\s+([^>]+)\/>/g)) {
    const attrs = Object.fromEntries([...text.matchAll(/([\w-]+)="([^"]*)"/g)].map(([, key, value]) => [key, value]));
    const shape = tag === 'path' ? ck.Path.MakeFromSVGString(attrs.d) : null;
    if (tag === 'path' && !shape) throw new Error('Invalid reference world path.');
    for (const mode of ['fill', 'stroke']) {
      if (!attrs[mode] || attrs[mode] === 'none') continue;
      const gradient = attrs[mode].match(/^url\(#(.+)\)$/)?.[1];
      if (gradient && !gradients[gradient]) throw new Error(`Unknown reference gradient: ${gradient}`);
      paint.setShader(gradient ? gradients[gradient] : null);
      paint.setColor(gradient ? ck.WHITE : color(attrs[mode], Number(attrs[`${mode}-opacity`] ?? 1)));
      paint.setStyle(mode === 'fill' ? ck.PaintStyle.Fill : ck.PaintStyle.Stroke);
      paint.setStrokeWidth(Number(attrs['stroke-width'] ?? 1));
      if (shape) canvas.drawPath(shape, paint);
      else canvas.drawCircle(Number(attrs.cx), Number(attrs.cy), Number(attrs.r), paint);
    }
    shape?.delete();
  }
  const vignette = ck.Shader.MakeLinearGradient([0, 0], [0, 820], [
    color('#050810', 0x44 / 255), color('#000000', 0), color('#050810', .2), color('#070b13'), color('#070b13'),
  ], [0, .3, .58, .95, 1], ck.TileMode.Clamp);
  paint.setShader(vignette); paint.setColor(ck.WHITE); paint.setStyle(ck.PaintStyle.Fill);
  canvas.drawRect(ck.XYWHRect(0, 0, 390, 820), paint);
  function writeSurface(target, file) {
    target.flush();
    const image = target.makeImageSnapshot(), bytes = image.encodeToBytes();
    if (!bytes) throw new Error(`Could not encode ${file}.`);
    fs.writeFileSync(file, bytes);
    image.delete();
  }
  writeSurface(surface, path.join(root, 'assets', 'images', 'arenas', 'relay-ritual.png'));
  surface.delete(); paint.delete(); vignette.delete();
  Object.values(gradients).forEach(shader => shader.delete());

  const output = path.join(root, 'assets', 'images', 'fighters', 'duplicates');
  fs.mkdirSync(output, { recursive: true });
  const gray = ck.ColorFilter.MakeMatrix([
    .2126, .7152, .0722, 0, 0, .2126, .7152, .0722, 0, 0,
    .2126, .7152, .0722, 0, 0, 0, 0, 0, 1, 0,
  ]);
  const entries = [];
  for (const id of ['arcane', 'shadow', 'sylva', 'titan', 'ember', 'frost']) {
    const image = ck.MakeImageFromEncoded(fs.readFileSync(path.join(root, 'assets', 'images', 'fighters', 'human', `${id}.png`)));
    if (!image) throw new Error(`Could not decode original Brawler ${id}.`);
    const target = ck.MakeSurface(image.width(), image.height());
    if (!target) throw new Error(`Could not create duplicate artwork for ${id}.`);
    const filterPaint = new ck.Paint();
    filterPaint.setColorFilter(gray);
    target.getCanvas().clear(ck.TRANSPARENT);
    target.getCanvas().drawImage(image, 0, 0, filterPaint);
    writeSurface(target, path.join(output, `${id}.png`));
    entries.push(`  ${id}: require('../../assets/images/fighters/duplicates/${id}.png'),`);
    filterPaint.delete(); target.delete(); image.delete();
  }
  gray.delete();
  fs.writeFileSync(path.join(root, 'src', 'assets', 'chest-ritual.ts'),
    `// Generated by scripts/build-chest-ritual.cjs from the Experience Board and original paintings.\n` +
    `export const ritualBackdrop = require('../../assets/images/arenas/relay-ritual.png');\n` +
    `export const duplicateBrawlers = {\n${entries.join('\n')}\n} as const;\n`);
  console.log('Built the reference Relay backdrop and six alpha-preserving grayscale duplicate paintings.');
}).catch(error => { console.error(error); process.exitCode = 1; });
