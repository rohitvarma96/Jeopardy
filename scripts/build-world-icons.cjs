const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ts = require('typescript');
const CanvasKitInit = require('canvaskit-wasm/bin/full/canvaskit.js');

const root = path.resolve(path.dirname(process.argv[1]), '..');
const sourcePath = path.join(root, 'src', 'assets', 'world-icon-paths.ts');
const data = {};
vm.runInNewContext(ts.transpileModule(fs.readFileSync(sourcePath, 'utf8'), {
  compilerOptions: { module: ts.ModuleKind.CommonJS },
}).outputText, { exports: data });

CanvasKitInit({}).then(ck => {
  const output = path.join(root, 'assets', 'images', 'world-icons');
  fs.mkdirSync(output, { recursive: true });
  const registry = [];
  for (const [name, svg] of Object.entries(data.worldIconPaths)) {
    const surface = ck.MakeSurface(96, 96);
    if (!surface) throw new Error('Could not create an icon raster surface.');
    const canvas = surface.getCanvas();
    canvas.clear(ck.TRANSPARENT);
    canvas.scale(3, 3);
    const shape = ck.Path.MakeFromSVGString(svg);
    if (!shape) throw new Error(`Invalid original icon path: ${name}`);
    const paint = new ck.Paint();
    paint.setColor(ck.WHITE);
    paint.setAntiAlias(true);
    paint.setStyle(ck.PaintStyle.Stroke);
    paint.setStrokeWidth(2);
    canvas.drawPath(shape, paint);
    surface.flush();
    const image = surface.makeImageSnapshot();
    const encoded = image.encodeToBytes();
    if (!encoded) throw new Error(`Could not encode icon: ${name}`);
    fs.writeFileSync(path.join(output, `${name}.png`), encoded);
    registry.push(`  '${name}': require('../../assets/images/world-icons/${name}.png'),`);
    image.delete(); paint.delete(); shape.delete(); surface.delete();
  }
  fs.writeFileSync(path.join(root, 'src', 'assets', 'world-icons.ts'),
    `// Generated by scripts/build-world-icons.cjs from the original vector paths.\nexport const worldIcons = {\n${registry.join('\n')}\n} as const;\n`);
  console.log(`Built ${registry.length} original 3x UI icons without runtime graphics contexts.`);
}).catch(error => { console.error(error); process.exitCode = 1; });
