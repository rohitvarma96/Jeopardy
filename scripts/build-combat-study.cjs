const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const vm = require('node:vm');

const root = path.resolve(path.dirname(process.argv[1]), '..');
const source = fs.readFileSync(path.join(root, 'src', 'components', 'fighters', 'combat', 'human-rig.ts'), 'utf8');
const compiled = ts.transpileModule(source, {
  compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.CommonJS },
}).outputText.replace(/^"use strict";\r?\n/, '');
if (compiled.includes('require(')) throw new Error('The portable rig study must not acquire runtime dependencies.');
const target = path.join(root, 'docs', 'design-assets', 'human-rig.js');
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, `// Generated by scripts/build-combat-study.cjs; edit the shared TypeScript source.\n(function () {\n'use strict';\nconst exports = {};\n${compiled}\nglobalThis.BrainBrawlHumanRig = exports;\n})();\n`);
const mesh = ts.transpileModule(fs.readFileSync(path.join(root, 'src', 'components', 'fighters', 'combat', 'painted-mesh.ts'), 'utf8'), {
  compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.CommonJS },
}).outputText.replace(/^"use strict";\r?\n/, '').replace(/\bvar __importDefault\b/, 'const __importDefault');
const coverage = fs.readFileSync(path.join(root, 'src', 'assets', 'painted-coverage.json'), 'utf8');
fs.appendFileSync(target, `(function () {\n'use strict';\nconst exports = {};\nconst require = (name) => { if (name === './human-rig') return globalThis.BrainBrawlHumanRig; if (name.endsWith('painted-coverage.json')) return ${coverage.trim()}; throw new Error('Unsupported painted rig dependency: ' + name); };\n${mesh}\nglobalThis.BrainBrawlPaintedMesh = exports;\n})();\n`);
const registry = {};
vm.runInNewContext(ts.transpileModule(fs.readFileSync(path.join(root, 'src', 'assets', 'human-fighters.ts'), 'utf8'), {
  compilerOptions: { module: ts.ModuleKind.CommonJS },
}).outputText, { exports: registry, require: source => source.replace('../../assets/', '../assets/') });
fs.appendFileSync(target, `globalThis.BrainBrawlPaintingSources = ${JSON.stringify(registry.humanFighters)};\n`);
const signaturePath = path.join(root, 'src', 'components', 'battle', 'signature-motion.ts');
const signatureAst = ts.createSourceFile(signaturePath, fs.readFileSync(signaturePath, 'utf8'), ts.ScriptTarget.Latest, true);
const pureSignature = ts.factory.updateSourceFile(signatureAst, signatureAst.statements.filter(node =>
  !ts.isImportDeclaration(node) && !(ts.isFunctionDeclaration(node) && node.name?.text === 'presentedPose')));
const signature = ts.transpileModule(ts.createPrinter().printFile(pureSignature), {
  compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.CommonJS },
}).outputText.replace(/^"use strict";\r?\n/, '');
if (signature.includes('require(')) throw new Error('Portable signature motion must not import game state.');
fs.appendFileSync(target, `(function () { const exports = {};\n${signature}\nglobalThis.BrainBrawlSignature = exports;\n})();\n`);
const fragments = fs.readFileSync(path.join(root, 'src', 'assets', 'brawler-fragments.json'), 'utf8');
fs.appendFileSync(target, `globalThis.BrainBrawlFragmentSources = ${fragments.trim()};\n`);
console.log('Built the portable study from shared anatomy, painted mesh, KO timing/noise, source-colored fragments and selection sources.');
